// Длина Московской кольцевой автомобильной дороги (км).
constexpr int MKAD_LENGTH = 109;

// Вычисляет отметку на МКАД, на которой окажется байкер
// через hours часов движения со скоростью speed км/ч,
// если он стартовал с нулевого километра.
//
// speed может быть отрицательной — это значит, что байкер
// едет в обратную сторону.
// hours — неотрицательное.
// Возвращает целое число в диапазоне [0, MKAD_LENGTH).
int positionOnMkad(int speed, int hours);
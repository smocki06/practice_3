#pragma once

// Возвращает число десятков — вторую справа цифру
// десятичной записи неотрицательного целого числа n.
// Если цифры десятков нет (n < 10), возвращает 0.
int tensDigit(unsigned long long n);

// Возвращает цифру, стоящую в позиции position
// (0 — единицы, 1 — десятки, 2 — сотни и т.д.).
int digitAt(unsigned long long n, int position);